import SwiftUI
import Foundation
import FirebaseFirestore

struct PostcardDetails: Codable, Identifiable {
    @DocumentID var id: String?

    var batchID: String
    var scannedAt: Date
    var status: PostcardStatus
    var frontImageURLString: String
    var backImageURLString: String
    var aiData: PostcardAIData
    
    var frontImageURL: URL? {
        URL(string: frontImageURLString)
    }

    var backImageURL: URL? {
        URL(string: backImageURLString)
    }
}

extension PostcardDetails {
    init(
        batchID: String,
        scannedAt: Date,
        frontImageURLString: String,
        backImageURLString: String,
        aiData: PostcardAIData
    ) {
        self.batchID = batchID
        self.scannedAt = scannedAt
        self.frontImageURLString = frontImageURLString
        self.backImageURLString = backImageURLString
        self.aiData = aiData

        self.status = Self.containsUnknownFields(in: aiData)
            ? .needsReview
            : .readyToList
    }
    
    private static let unknownValues = ["Unknown", "Unposted", "None"]
    
    // boolean function that returns whether fields generated by ai contain unknown values. meaning ai wasn't able to successfully extract data
    private static func containsUnknownFields(in data: PostcardAIData) -> Bool {
        let fieldsToCheck = [
            data.era,
            data.type.material,
            data.type.style
        ]
        
        let hasUnknownField = fieldsToCheck.contains { field in
            let trimmedField = field.trimmingCharacters(in: .whitespacesAndNewlines)
            
            return trimmedField.isEmpty || unknownValues.contains { unknownValue in
                trimmedField.localizedCaseInsensitiveContains(unknownValue)
            }
        }
        
        return hasUnknownField
    }
    
    // must be mutating to change its properties
    mutating func update(aiData newAIData: PostcardAIData) {
        aiData = newAIData

        // Once a postcard is listed or sold, editing its details shouldn't change its status
        if status == .needsReview || status == .readyToList {
            status = Self.containsUnknownFields(in: newAIData) ? .needsReview : .readyToList
        }
    }
}

enum PostcardStatus: String, Codable, CaseIterable {
    case needsReview = "needs review"
    case readyToList = "ready to list"
    case listed = "listed"
    case sold = "sold"
}

extension PostcardStatus {
    var color: Color {
        switch self {
        case .needsReview:
            return .red
        case .readyToList:
            return .yellow
        case .listed:
            return .blue
        case .sold:
            return .green
        }
    }
}

